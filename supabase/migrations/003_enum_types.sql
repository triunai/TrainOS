-- ─── Verify ─────────────────────────────────────────────────────────────────

DO $verify$
DECLARE
  v_types  int;
  v_labels int;
  v_bad    text;
BEGIN
  SELECT count(*) INTO v_types
  FROM pg_catalog.pg_type t
  JOIN pg_catalog.pg_namespace n ON n.oid = t.typnamespace
  WHERE n.nspname = 'core' AND t.typtype = 'e';
  IF v_types <> 69 THEN
    RAISE EXCEPTION '003 verify: expected 69 enum types in core, found %', v_types;
  END IF;

  SELECT count(*) INTO v_labels
  FROM pg_catalog.pg_enum e
  JOIN pg_catalog.pg_type t ON t.oid = e.enumtypid
  JOIN pg_catalog.pg_namespace n ON n.oid = t.typnamespace
  WHERE n.nspname = 'core';
  IF v_labels < 200 THEN
    RAISE EXCEPTION '003 verify: only % enum labels in core; expected ~280', v_labels;
  END IF;

  -- Every type carries the COMMENT that records where its values came from. An
  -- uncommented type is one somebody added by hand, which is exactly the case
  -- this migration exists to prevent.
  SELECT string_agg(t.typname, ', ') INTO v_bad
  FROM pg_catalog.pg_type t
  JOIN pg_catalog.pg_namespace n ON n.oid = t.typnamespace
  WHERE n.nspname = 'core' AND t.typtype = 'e'
    AND obj_description(t.oid, 'pg_type') IS NULL;
  IF v_bad IS NOT NULL THEN
    RAISE EXCEPTION '003 verify: enum type(s) with no provenance comment: %', v_bad;
  END IF;

  -- The two identity types must NOT have been duplicated into core. Two
  -- `actor_kind` types, one in app and one in core, is the divergence that ends
  -- with a column typed against the wrong one and a cast that silently works.
  IF EXISTS (
    SELECT 1 FROM pg_catalog.pg_type t
    JOIN pg_catalog.pg_namespace n ON n.oid = t.typnamespace
    WHERE n.nspname = 'core' AND t.typname IN ('actor_kind','app_role')
  ) THEN
    RAISE EXCEPTION
      '003 verify: actor_kind or app_role was created in core. Doc 02 owns both '
      'and creates them in app; a second copy is a silent mistyping waiting to happen.';
  END IF;

  RAISE NOTICE '003 verify: OK - % enum types, % labels, all commented.', v_types, v_labels;
END;
$verify$;

COMMIT;
