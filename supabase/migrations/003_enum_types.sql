-- ============================================================================
-- Migration 003: enum types — the closed catalogues the API contract froze,
-- generated FROM the contract package so the two cannot disagree.
-- ============================================================================
--
-- FEATURE. Doc 01's Conventions section makes a deliberate split:
--
--   Closed catalogues (§12 and §17 of the contract) become native Postgres
--   enums. They are frozen by the contract, so the cost of ALTER TYPE never
--   arrives; they generate real union types in Supabase's TypeScript output,
--   which is the entire point of having a contract package; and they are four
--   bytes on disk in a model with a great many status columns.
--
--   Open, config-driven sets become `text` with a foreign key to a reference
--   table. Never `text + CHECK`. The project rule is that stage names and order
--   render from configuration, never hardcoded — a CHECK constraint is code, a
--   reference table is data: editable by an admin screen, joinable for labels
--   and ordering, and still enforced by an FK. Those sets are `action_type`,
--   the lifecycle step key, the compliance check key, `hrdc_document_type`,
--   the metric key, the tier key, the template type and the TNA constraint code.
--   They arrive in 004 as tables, not here as types.
--
-- WHY THIS IS GENERATED AND NOT TRANSCRIBED
--
-- Sixty-nine types and roughly two hundred and eighty values. Transcribing that
-- by hand produces a typo in a value nobody notices until a row will not insert
-- in staging, and the failure is silent at authoring time because a misspelt
-- enum label is perfectly valid SQL. Sixty-two of the sixty-nine are therefore
-- generated by reading `packages/contract/src/enums.ts` and emitting one
-- CREATE TYPE per `as const` array, so the database and the TypeScript contract
-- are the same list by construction rather than by review. Each carries a
-- COMMENT naming the exact constant it came from, so the provenance survives
-- into `psql \dT+`.
--
-- The remaining seven are named by doc 01 with inline values but are absent
-- from the package. They are listed separately below, each with the doc section
-- it came from, and they are the ones to re-check when the package catches up.
-- ⚠ `travel_region` is the weakest: doc 01 names the type but gives no values,
-- so the three below are taken from DECISIONS §5's rate-card travel bands
-- (Klang Valley / peninsular / East Malaysia). Flagged in the report.
--
-- ⚠ CONFLICT C3, resolved. Doc 03 §1 states its own convention: "check
-- constraints in place of enum types so that adding a value is a migration on
-- one line rather than a type rewrite", and writes every `app.*` gate table
-- that way. Doc 01 makes the opposite choice, with reasons, for the domain.
-- These are not in conflict: each document is describing the tables it owns.
-- The gate tables in 011 use `text` + CHECK exactly as doc 03 writes them; the
-- domain tables use these enums. The asymmetry is deliberate and is recorded
-- here so a later reader does not "unify" it in one direction and break the
-- other lane's stated design.
--
-- ⚠ `app_role` and `actor_kind` are NOT created here. Doc 02 §1.2 creates them
-- in `app`, and doc 02 outranks doc 01 on identity. A domain column typed
-- `actor_kind` therefore uses `app.actor_kind`. Recorded as conflict C2.
--
-- SPINE: none touched. Types only; no table, no function, no policy.
--
-- ── AUTHORIZATION ─────────────────────────────────────────────────────────
--   Types are not privileged objects. USAGE on a type is granted to PUBLIC by
--   default and there is nothing sensitive in a label. What matters is that
--   `core` itself is reachable, which 001 arranged, and that PUBLIC holds no
--   CREATE there, which 001 also arranged and test_001 T4b asserts.
--
-- ── THE 7-POINT RPC CONTRACT CHECK, worked ───────────────────────────────
--   1. Envelope: no RPC. 2. Unwrap: no jsonb crosses the boundary.
--   3. RpcMap: none — but this migration is the one place the SQL side and
--      `packages/contract/src/enums.ts` MUST stay in lockstep, and it is
--      generated from that file precisely so they do. test_003 re-derives the
--      comparison at run time rather than trusting the generation.
--   4. Call sites: every domain table in 004-013 types a column with one of
--      these. Zero today is expected.
--   5. Casts: none. 6. Reload/restore: no behaviour. 7. Public routes: none.
--
-- ⚠ OPERATIONAL NOTE THAT OUTLIVES THIS MIGRATION. A Postgres enum value can be
-- ADDED (`ALTER TYPE ... ADD VALUE`) but not removed or reordered, and before
-- PostgreSQL 12 ADD VALUE could not run inside a transaction at all. Adding a
-- value is therefore cheap and removing one is a table rewrite. That asymmetry
-- is the reason only CLOSED catalogues are enums: if a set is going to lose a
-- member, it should have been a reference table.
--
-- Rollback: rollbacks/003_enum_types_rollback.sql
-- ============================================================================

